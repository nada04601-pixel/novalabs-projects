const monthlyRow = ([dep, rent]: [number, number]) => {
  const r = calcBrokerage("monthly", 0, dep, rent);
  const x100 = dep + rent * 100;
  return [
    `${krw(dep)} / ${krw(rent)}`,
    krw(x100),
    r.dealAmount === x100 ? krw(r.dealAmount) : `${krw(r.dealAmount)} (×70)`,
    r.limit ? `${pr(r.rate)} (한도 ${krw(r.limit)})` : pr(r.rate),
    won(r.fee),
  ];
};
