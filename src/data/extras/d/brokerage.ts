const fee = (type: DealType, amount: number) => calcBrokerage(type, amount, 0, 0);
const vatIncl = (f: number) => f + Math.floor(f * 0.1);

const tableRow = (type: DealType, amount: number) => {
  const r = fee(type, amount);
  return [krw(amount), pr(r.rate), r.limit ? krw(r.limit) : "없음", won(r.fee), won(r.fee + r.vat)];
};

