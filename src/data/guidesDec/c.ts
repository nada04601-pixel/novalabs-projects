const n = (v: number) => Math.round(v).toLocaleString("ko-KR");
const f1 = (v: number) => Number(v.toFixed(1)).toLocaleString("ko-KR");
const f2 = (v: number) => Number(v.toFixed(2)).toLocaleString("ko-KR");
const pct = (v: number, d = 0) => `${(v * 100).toFixed(d)}%`;
// 파일 크기: 1KB = 1,024바이트. 1,024MB 이상은 GB로 보여 줍니다.
const sz = (bytes: number) =>
  bytes >= 1024 ** 3 ? `${f2(bytes / 1024 ** 3)}GB` : bytes >= 1024 ** 2 ? `${f1(bytes / 1024 ** 2)}MB` : `${n(bytes / 1024)}KB`;

// 압축 전 크기: 화소 하나에 빨강·초록·파랑 8비트씩, 3바이트(24비트).
// 출처: MDN Image file type and format guide(JPEG 항목 "each of which is 8 bits"), 확인 2026-11-27
const RGB_BYTES = 3;
const rawBytes = (w: number, h: number) => w * h * RGB_BYTES;

// ───────────── 1. 사진 용량 줄이기 (image-compress) ─────────────
// 예로 드는 원본: 가로 4,000 × 세로 3,000px(1,200만 화소) 사진
const PHOTO = { w: 4000, h: 3000 };
const photoRaw = rawBytes(PHOTO.w, PHOTO.h);
// 도구의 크기 조절(outputSize)과 같은 계산으로 긴 변을 줄인 크기
const longSides = [4000, 3000, 1920, 1280, 1024, 800];
const resized = longSides.map((long) => {
  const s = outputSize(PHOTO.w, PHOTO.h, { mode: "long", value: long });
  return { long, ...s, px: s.w * s.h, raw: rawBytes(s.w, s.h) };
});
// 목표 용량: 도구의 parseTargetSize와 같은 기준(1KB = 1,024바이트)
