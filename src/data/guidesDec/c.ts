const GIF_MAX_COLORS = 2 ** (7 + 1);
const GIF_SRC = { w: 1920, h: 1080 }; // 16:9 원본 예
const GIF_LEN = 5; // 도구가 처음 골라 두는 길이(앞 5초)
const gifCases = GIF_WIDTHS.flatMap((w) =>
  GIF_FPS.map((fps) => {
    const s = gifSize(GIF_SRC.w, GIF_SRC.h, w);
    const frames = frameTimes(0, GIF_LEN, fps).length;
    return { sel: w, fps, ...s, frames, raw: s.w * s.h * frames, est: estimateGifBytes(s.w, s.h, frames) };
  }),
);
const gifDefault = gifCases.find((c) => c.sel === 480 && c.fps === 12)!;
const delayRows = GIF_FPS.map((fps) => {
  const d = gifDelay(fps);
  return [`${fps}fps`, `${n(1000 / fps)}ms`, `${n(d)}ms(${d / 10}/100초)`, `약 ${f1(1000 / d)}fps`];
});
// 같은 화면을 짧은 MP4로 만들 때: 동영상 용량 줄이기 도구의 계산식(화소 × fps × 화소당 0.08비트, '권장' 설정)으로 어림
const MP4_BPP = COMPRESS_PRESETS.medium.bpp;
const mp4Cases = [
  { w: 480, fps: 12, sec: 5 },
  { w: 480, fps: 15, sec: 10 },
  { w: 640, fps: 15, sec: 20 },
].map((c) => {
  const s = gifSize(GIF_SRC.w, GIF_SRC.h, c.w);
  const frames = frameTimes(0, c.sec, c.fps).length;
  const gif = estimateGifBytes(s.w, s.h, frames);
  const mp4 = estimateBytes(Math.max(150_000, s.w * s.h * 30 * MP4_BPP), 0, c.sec);
  return { ...c, ...s, gif, mp4 };
});
